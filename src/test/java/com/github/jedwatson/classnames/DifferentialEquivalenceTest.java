package com.github.jedwatson.classnames;

import java.io.InputStream;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * PHASE 11 - behavioral equivalence gate.
 *
 * <p>Replays a corpus of argument lists that was executed against the ORIGINAL JavaScript
 * implementation, and asserts the Java output is byte-identical for all four entry points
 * ({@code index.js}, {@code bind.js} unbound, {@code bind.js} bound, {@code dedupe.js}).
 *
 * <p>Corpus and expected outputs are generated by
 * {@code verification/generate-baseline.mjs} and must never be hand-edited: the
 * JavaScript implementation is the source of truth. Regenerate with:
 * <pre>{@code node verification/generate-baseline.mjs}</pre>
 *
 * <p>This is stronger evidence than the migrated unit tests alone, which only cover the
 * 63 cases the upstream authors happened to write. The corpus additionally probes
 * truthiness, key ordering, whitespace splitting, {@code toString} dispatch, deep
 * recursion, Unicode and dedupe toggling.
 */
class DifferentialEquivalenceTest {

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private static final JsonNode CORPUS = load("/corpus.json");
    private static final JsonNode EXPECTED = load("/expected.json");

    private static final ClassNamesBind BOUND = ClassNamesBind.bind(bindings());

    private static JsonNode load(String resource) {
        try (InputStream in = DifferentialEquivalenceTest.class.getResourceAsStream(resource)) {
            assertNotNull(in, "Missing test resource " + resource
                    + " - run `node verification/generate-baseline.mjs` first");
            return MAPPER.readTree(in);
        } catch (Exception e) {
            throw new IllegalStateException("Unable to read " + resource, e);
        }
    }

    private static Map<String, Object> bindings() {
        Map<String, Object> map = new LinkedHashMap<>();
        JsonNode node = CORPUS.get("bindings");
        node.fieldNames().forEachRemaining(name -> {
            JsonNode value = node.get(name);
            map.put(name, value.isNumber() ? value.intValue() : value.asText());
        });
        return map;
    }

    /**
     * Decodes the tagged value encoding described in
     * {@code verification/generate-baseline.mjs}.
     *
     * <p>The encoding exists because JSON cannot represent {@code undefined}, {@code NaN},
     * {@code -0}, guaranteed key order, or a custom {@code toString}.
     */
    private static Object decode(JsonNode node) {
        String type = node.get("t").asText();
        return switch (type) {
            case "str" -> node.get("v").asText();
            case "int" -> node.get("v").intValue();
            case "num" -> node.get("v").doubleValue();
            case "nan" -> Double.NaN;
            case "negzero" -> -0.0d;
            case "bool" -> node.get("v").booleanValue();
            // JS null and undefined both map to Java null: both are falsy, and this
            // library never distinguishes them observably.
            case "null", "undef" -> null;
            case "arr" -> {
                List<Object> elements = new ArrayList<>();
                for (JsonNode child : node.get("v")) {
                    elements.add(decode(child));
                }
                yield elements;
            }
            case "obj" -> {
                // Ordered pairs, so insertion order is exactly what JavaScript saw.
                Map<String, Object> target = new LinkedHashMap<>();
                for (JsonNode pair : node.get("v")) {
                    target.put(pair.get(0).asText(), decode(pair.get(1)));
                }
                yield target;
            }
            case "fn" -> (java.util.function.Supplier<String>) () -> "fn";
            case "tostr" -> new CustomToString(node.get("v").asText());
            case "inherited" -> new InheritedToString(node.get("v").asText());
            default -> throw new IllegalArgumentException("Unknown encoded type: " + type);
        };
    }

    static Stream<Arguments> corpus() {
        List<Arguments> arguments = new ArrayList<>();
        JsonNode cases = CORPUS.get("cases");
        JsonNode results = EXPECTED.get("results");

        for (int i = 0; i < cases.size(); i++) {
            JsonNode testCase = cases.get(i);
            JsonNode expected = results.get(i);
            String id = testCase.get("id").asText();

            assertEquals(id, expected.get("id").asText(),
                    "corpus.json and expected.json are out of sync at index " + i);

            List<Object> args = new ArrayList<>();
            for (JsonNode arg : testCase.get("args")) {
                args.add(decode(arg));
            }
            arguments.add(Arguments.of(id, args, expected));
        }
        return arguments.stream();
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("corpus")
    @DisplayName("Java output matches the JavaScript implementation")
    void matchesJavaScript(String id, List<Object> args, JsonNode expected) {
        Object[] argv = args.toArray();

        assertEquals(expected.get("classNames").asText(),
                ClassNames.classNames(argv),
                "index.js mismatch for case: " + id);

        assertEquals(expected.get("bindUnbound").asText(),
                ClassNamesBind.classNames(argv),
                "bind.js (unbound) mismatch for case: " + id);

        assertEquals(expected.get("bindBound").asText(),
                BOUND.apply(argv),
                "bind.js (bound) mismatch for case: " + id);

        assertEquals(expected.get("dedupe").asText(),
                ClassNamesDedupe.classNames(argv),
                "dedupe.js mismatch for case: " + id);
    }

    @Test
    @DisplayName("corpus is substantial enough to be meaningful")
    void corpusIsNotTrivial() {
        // Guards against a truncated or partially regenerated corpus silently
        // weakening this gate.
        assertTrue(CORPUS.get("cases").size() >= 70,
                "Corpus shrank unexpectedly: " + CORPUS.get("cases").size() + " cases");
        assertEquals(CORPUS.get("cases").size(), EXPECTED.get("results").size());
    }

    @Test
    @DisplayName("unbound bind entry point matches plain classNames on the whole corpus")
    void unboundBindMatchesPlain() {
        // bind.js with `this` undefined degrades to index.js behavior. Asserting it
        // across the corpus pins that equivalence rather than assuming it.
        for (JsonNode testCase : CORPUS.get("cases")) {
            List<Object> args = new ArrayList<>();
            for (JsonNode arg : testCase.get("args")) {
                args.add(decode(arg));
            }
            Object[] argv = args.toArray();
            assertEquals(ClassNames.classNames(argv), ClassNamesBind.classNames(argv),
                    "Divergence for case: " + testCase.get("id").asText());
        }
    }

    /** Models a JS object literal carrying an own {@code toString}. */
    static class CustomToString {
        private final String literal;

        CustomToString(String literal) {
            this.literal = literal;
        }

        @Override
        public String toString() {
            return literal;
        }
    }

    /** Models a class instance inheriting {@code toString} from a superclass. */
    static class InheritedToString extends CustomToString {
        InheritedToString(String literal) {
            super(literal);
        }
    }
}
